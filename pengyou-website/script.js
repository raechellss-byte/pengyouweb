function cardHTML(r, l, clone) {
  return `
    <article class="rcard"${clone ? ' aria-hidden="true"' : ''}>
      <p>${r[l === 'en' ? 'en' : 'id']}</p>
      <footer>
        <div class="rname"><b>${r.n}</b><small>${r[l === 'en' ? 'roleEn' : 'roleId']}</small></div>
        <span class="avatar avatar--${r.g}" aria-hidden="true">${AVATAR[r.g]}</span>
      </footer>
    </article>`;
}
function renderReviews(l) {
  const t = $('#reviewTrack');
  if (!t) return;
  const frac = revSet ? ((t.scrollLeft - revSet) % revSet + revSet) % revSet / revSet : 0;
  t.innerHTML = [0, 1, 2].map(i => REVIEWS.map(r => cardHTML(r, l, i !== 1)).join('')).join('');
  measureReviews(frac);
}
function measureReviews(frac = 0) {
  const t = $('#reviewTrack');
  if (!t || !t.children.length) return;
  revSet = t.children[REVIEWS.length].offsetLeft - t.children[0].offsetLeft; // lebar 1 set
  t.scrollLeft = revSet + frac * revSet;
}
(function initReviewScroll() {
  const t = $('#reviewTrack'), dots = $$('#reviewDots i');
  if (!t) return;
  measureReviews();
  addEventListener('load', () => measureReviews());
  addEventListener('resize', () => measureReviews());
  const wrap = () => {
    if (t.scrollLeft < revSet * .5) t.scrollLeft += revSet;
    else if (t.scrollLeft > revSet * 1.5) t.scrollLeft -= revSet;
  };
  // drag dengan mouse (touch & trackpad memakai scroll bawaan browser)
  let down = false, sx = 0, sl = 0;
  t.addEventListener('pointerdown', e => { if (e.pointerType !== 'mouse') return; down = true; sx = e.clientX; sl = t.scrollLeft; t.classList.add('drag'); });
  addEventListener('pointermove', e => { if (down) t.scrollLeft = sl - (e.clientX - sx); });
  addEventListener('pointerup', () => { down = false; t.classList.remove('drag'); });
  t.addEventListener('dragstart', e => e.preventDefault());
  // Catatan: roda mouse vertikal TIDAK dibajak, jadi scroll halaman tidak pernah tersangkut.
  const step = () => t.clientWidth * .8;
  $('#revPrev').addEventListener('click', () => t.scrollBy({ left: -step(), behavior: 'smooth' }));
  $('#revNext').addEventListener('click', () => t.scrollBy({ left: step(), behavior: 'smooth' }));
  t.addEventListener('scroll', () => {
    wrap();
    const p = (((t.scrollLeft - revSet) % revSet) + revSet) % revSet / revSet;
    const a = Math.min(dots.length - 1, Math.floor(p * dots.length));
    dots.forEach((d, i) => d.classList.toggle('on', i === a));
  }, { passive: true });
})();

